def find_chrome():
    for name in ("google-chrome", "chromium-browser", "chromium"):
        path = shutil.which(name)
        if path is not None:
            return path
    raise RuntimeError(
        "No Chrome/Chromium binary found (tried google-chrome, "
        "chromium-browser, chromium). Install one to build this PDF."
    )


def main():
    html_path = os.path.join(os.path.dirname(__file__), "_umi_data_collection_manual.tmp.html")
    with open(html_path, "wb") as f:
        f.write(base64.b64decode(HTML_B64))

    try:
        subprocess.run(
            [
                find_chrome(),
                "--headless",
                "--disable-gpu",
                "--no-sandbox",
                f"--print-to-pdf={OUT_PDF}",
                "--print-to-pdf-no-header",
                "--no-pdf-header-footer",
                "--virtual-time-budget=10000",
                f"file://{html_path}",
            ],
            check=True,
        )
    finally:
        os.remove(html_path)

    print(f"Wrote {OUT_PDF}")


if __name__ == "__main__":
    main()
